import assert from 'node:assert/strict';
import {selectDailyTargets,selectLevelReviews,scheduledLowerRetention,RETENTION_POLICY,recordLearningEvidence,researchSchedule,initRealtimeLevel,observeRealtimeLevel,calibratedWord} from '../lib/learning-model.js';
import {buildDailyPlan,nextUsagePlan} from '../lib/daily-practice.js';
import {authoredCurriculum} from '../api/authored-bank.js';
import {AUTHORED_OWNER} from '../lib/authored-policy.js';
import {authoredEntry} from '../api/authored-bank.js';
import {prepare} from '../api/prepare-worker.js';
import {passageKeys} from '../lib/prepared-plan.js';
const words=authoredCurriculum(AUTHORED_OWNER).map(w=>calibratedWord({w:w.word,d:w.definition,band:w.band,cat:w.domain}));
const low=words.find(w=>w.w==='비교'),near=words.filter(w=>w.band===4).slice(0,10),day='2026-10-13';
const learner={difficulty:4,words:Object.fromEntries(near.map(w=>[w.w,{seen:1,nextReviewAt:day,useSuccess:1}]))};
learner.words[low.w]={seen:3,useSuccess:1,usageConfirmedAt:'2026-10-01',introducedAt:'2026-10-01',lastExposureAt:'2026-10-05',lastFeedbackDate:'2026-10-05',nextReviewAt:'2026-10-08'};
assert.ok(scheduledLowerRetention(low,learner,day));
const before=JSON.stringify(learner),selected=selectDailyTargets(words,learner,day,{newCount:5,reviewCount:10});
assert.equal(selected.newWords.length,5);assert.equal(selected.reviewWords.length,10);
assert.equal(selected.reviewWords.filter(w=>w.retentionPolicy===RETENTION_POLICY).length,1);
assert.equal(selected.coverage.words.length,1,'coverage and learned-word retention both keep a slot');
assert.equal(JSON.stringify(learner),before);
const plans=buildDailyPlan(selected.newWords,selected.reviewWords,w=>learner.words[w],4);
const p=plans.find(p=>p.w.w===low.w);assert.equal(p.type,'subjective_recall');assert.equal(p.levelEligible,false);assert.equal(p.needsCard,false);assert.equal(p.practiceOnly,false);
const active={mode:'daily',results:[]};initRealtimeLevel(learner,active);
const st=learner.words[low.w],rec={word:low.w,band:low.band,type:p.type,credit:1,targetRecall:true,contextSuccess:true,practiceOnly:false,levelEligible:false};
const evidence=recordLearningEvidence(learner,st,{w:low,type:p.type,showTarget:false},rec,day);researchSchedule(st,evidence,rec,day);
assert.ok(st.independentRecallDays.includes(day));assert.ok(st.retention7.success>=1);assert.equal(st.nextReviewAt,'2026-10-14');
active.results.push(rec);observeRealtimeLevel(learner,active);assert.equal(learner.difficulty,4);assert.equal(active.adaptation.rows.length,0);
assert.equal(nextUsagePlan(p,[rec],plans.length,st).type,'subjective_use','recall alone does not finish daily use');
assert.equal(scheduledLowerRetention(low,learner,day),false,'same-day repeats do not occupy retention slots');
assert.equal(selectLevelReviews([low],learner,10,day).length,0);
assert.ok(scheduledLowerRetention(low,{...learner,difficulty:8},'2026-10-14'),'rapid promotion cannot drop a learned word');
assert.equal(scheduledLowerRetention({...low,band:1},learner,'2026-10-14'),false);
const noSchedule={difficulty:7.4,words:{[low.w]:{seen:1,useSuccess:1}}};
assert.equal(scheduledLowerRetention(low,noSchedule,day),false,'legacy success counters do not invent a scheduled review');
const exhausted=JSON.parse(before);exhausted.words[low.w].usedPassageKeys=[];
for(let i=0;i<3;i++){
 const entry=authoredEntry({...p,id:String(i)},exhausted,AUTHORED_OWNER);
 assert.ok(entry);exhausted.words[low.w].usedPassageKeys.push(...passageKeys(entry.question.ctx,[]));
}
const packet=await prepare({id:'retention-exhausted',kind:'reserve',slot:1,account:AUTHORED_OWNER,profile:'test',learner:exhausted,curriculum:[],catalog:{}},'fixture',async()=>{throw Error('Retention must not wait for new generation')},async()=>true);
assert.equal(packet.plans.find(p=>p.w.w===low.w).type,'subjective_recall');
assert.equal(packet.ready.length,packet.plans.length,'exhausted recall stays unprompted without live generation');
console.log('Long-term retention verified: overdue learned words survive promotion, share bounded slots with unfinished vocabulary, require recall then own sentences, accrue spaced evidence without grade inflation, and never revive retired words.');

